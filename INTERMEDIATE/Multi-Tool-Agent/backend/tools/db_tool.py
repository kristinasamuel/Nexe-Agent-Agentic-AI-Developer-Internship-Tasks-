import os
import psycopg2
from datetime import datetime
from agents import function_tool
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

def get_connection():
    if not DATABASE_URL:
        raise ValueError("DATABASE_URL not found in .env file")
    return psycopg2.connect(DATABASE_URL)

# Initialize table - Wrapped in a try/except to prevent backend crash
def init_db():
    try:
        conn = get_connection()
        cur = conn.cursor()
        cur.execute("""
            CREATE TABLE IF NOT EXISTS interactions (
                id SERIAL PRIMARY KEY,
                user_query TEXT,
                agent_response TEXT,
                timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.commit()
        cur.close()
        conn.close()
        print("✅ Database initialized successfully.")
    except Exception as e:
        print(f"❌ Database initialization failed: {e}")
        print("The app will continue to run, but database features may not work.")

# Call init_db safely
init_db()

@function_tool
def save_to_db(user_query: str, agent_response: str):
    """
    Saves the user's query and the agent's response to the Neon PostgreSQL database.
    
    Args:
        user_query (str): The query or message from the user.
        agent_response (str): The response generated by the agent.
    """
    try:
        conn = get_connection()
        cur = conn.cursor()
        cur.execute(
            "INSERT INTO interactions (user_query, agent_response) VALUES (%s, %s)",
            (user_query, agent_response)
        )
        conn.commit()
        cur.close()
        conn.close()
        return {"status": "success", "message": "Data saved to database successfully."}
    except Exception as e:
        print(f"Database Save Error: {e}")
        return {"status": "error", "message": str(e)}
